"""
atlas_schema.py — MongoDB Atlas collection schemas and index setup

Run once to create indexes:
    python atlas_schema.py

Collections:
    cdvae.users       — user accounts
    cdvae.structures  — generated crystal structures per user
"""

import os
import asyncio
from motor.motor_asyncio import AsyncIOMotorClient
from dotenv import load_dotenv 

MONGO_URI = os.getenv("MONGO_URI", "mongodb://localhost:27017")
MONGO_DB  = os.getenv("MONGO_DB",  "cdvae")


# ══════════════════════════════════════════════════════════════════════════════
