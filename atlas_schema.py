# ══════════════════════════════════════════════════════════════════════════════
#  INDEX SETUP
#  Run this once after creating your Atlas cluster.
# ══════════════════════════════════════════════════════════════════════════════

async def create_indexes():
    client = AsyncIOMotorClient(MONGO_URI)
    db     = client[MONGO_DB]

    print(f"Connecting to Atlas: {MONGO_DB}")

    # ── users collection ──────────────────────────────────────────────────────
    # Unique index on username — enforced at DB level, not just app level
    await db["users"].create_index(
        "username",
        unique=True,
        name="username_unique"
    )
    print("✓  users.username  — unique index")

    # Optional: unique sparse index on email (sparse = allows multiple null)
    await db["users"].create_index(
        "email",
        unique=True,
        sparse=True,
        name="email_unique_sparse"
    )
    print("✓  users.email     — unique sparse index")

    # ── structures collection ─────────────────────────────────────────────────
    # Compound index: filter by user + sort by time — covers GET /structures
    await db["structures"].create_index(
        [("username", 1), ("created_at", -1)],
        name="username_created_at"
    )
    print("✓  structures.(username, created_at) — compound index")

    # Index for delete by label + username
    await db["structures"].create_index(
        [("username", 1), ("label", 1)],
        name="username_label"
    )
    print("✓  structures.(username, label) — compound index")

    # Index for querying by element composition
    await db["structures"].create_index(
        "requested_elements",
        name="requested_elements"
    )
    print("✓  structures.requested_elements — multikey index")

    print("\nAll indexes created successfully.")
    client.close()


if __name__ == "__main__":
    asyncio.run(create_indexes())
